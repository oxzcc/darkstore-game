// Тележка сборщика (W7, решение автора 16.10, вариант «а») — как в концепт-рендере «Даркстор: Moving Out-стиль»:
// серый каркас 0,72 × 0,9 м, высокие задние стойки с ручкой, нижняя полка, крупная зелёная корзина, тёмные колёсики.
// Корзина полая и пустая: товары внутри пока не показываем (на рендере в корзине и на полке лежали коробки).
// Координаты своей тележки: центр — (0, 0, 0), ручка — к −z (к сборщику). Где она стоит на складе — scene/pickerPose.ts.
import { PALETTE } from '../../config/palette';
import type { VoxelPart } from './ProductItem';

export function cartParts(): VoxelPart[] {
  const p: VoxelPart[] = [];
  /** Брусок: размеры, цвет, x, y — низ бруска, z. */
  const rb = (w: number, h: number, d: number, color: string, x: number, y: number, z: number) =>
    p.push({ pos: [x, y + h / 2, z], size: [w, h, d], color });
  const F = PALETTE.cartFrame;
  for (const sx of [-1, 1]) {
    rb(0.06, 1.05, 0.06, F, sx * 0.33, 0, -0.48);   // задняя стойка — за корзиной, до ручки
    rb(0.06, 0.06, 0.96, F, sx * 0.33, 0.1, -0.03); // нижняя рама
    rb(0.06, 0.5, 0.06, F, sx * 0.33, 0.1, 0.42);  // передняя стойка — до дна корзины
    for (const sz of [-1, 1]) rb(0.06, 0.14, 0.14, PALETTE.wheel, sx * 0.33, 0, sz * 0.4); // колёсико
  }
  rb(0.72, 0.05, 0.05, F, 0, 1.0, -0.48);          // ручка
  rb(0.72, 0.04, 0.85, F, 0, 0.2, 0);              // нижняя полка
  // корзина — полая (правка автора 16.10: сплошной блок не давал глубины): дно, четыре стенки, прорези снаружи
  const [W, H, D, T] = [0.78, 0.42, 0.9, 0.05]; // ширина, высота, глубина, толщина стенки
  const y0 = 0.6;
  rb(W, T, D, PALETTE.uniformDark, 0, y0, 0);                              // дно (темнее — видно, что внутри пусто)
  for (const sx of [-1, 1]) rb(T, H, D, PALETTE.uniform, sx * (W - T) / 2, y0, 0);        // боковые стенки
  for (const sz of [-1, 1]) rb(W - 2 * T, H, T, PALETTE.uniform, 0, y0, sz * (D - T) / 2); // торцы
  // прорези: тёмные полоски на внешней стороне стенок
  const slot = PALETTE.uniformDark;
  for (const sx of [-1, 1]) for (const z of [-0.27, -0.09, 0.09, 0.27]) rb(0.012, 0.2, 0.08, slot, sx * (W / 2 + 0.004), y0 + 0.11, z);
  for (const sz of [-1, 1]) for (const x of [-0.2, 0, 0.2]) rb(0.08, 0.2, 0.012, slot, x, y0 + 0.11, sz * (D / 2 + 0.004));
  return p;
}
