// Товар на полке — заглушка из кубов (M5d, решение автора 12.10: упрощённые воксельные формы разного цвета).
// Позже их заменят воксельные иконки/модели товаров (08, раздел 9). Форма и цвета — из config/products.ts.
// Возвращает список кубов, а не компонент: товаров на складе сотни, поэтому их рисует
// один общий VoxelBatch через instancing (08, раздел 11).
import type { ProductLook } from '../../model/product';

/** Один кубик: центр и размер в метрах, цвет. */
export type VoxelPart = { pos: [number, number, number]; size: [number, number, number]; color: string };

/**
 * Кубики одной штуки товара шириной `w` метров. Координаты: x — вдоль полки, y — вверх от полки (0 — доска),
 * z — к лицу стеллажа (+z — сторона, откуда смотрит сборщик). Глубина товара не больше `w * 1.5`.
 */
export function productParts(look: ProductLook, w: number): VoxelPart[] {
  const { color: c, accent: a } = look;
  const box = (x: number, y: number, z: number, sx: number, sy: number, sz: number, color: string): VoxelPart =>
    ({ pos: [x * w, y, z * w], size: [sx * w, sy, sz * w], color });
  // y и высоты — в метрах, остальное — в долях ширины товара

  switch (look.shape) {
    case 'carton': // пакет: высокий брусок, двускатный верх, полоса этикетки на лице
      return [
        box(0, 0.11, 0, 0.8, 0.22, 0.8, c),
        box(0, 0.24, 0, 0.8, 0.04, 0.3, c),
        box(0, 0.11, 0.41, 0.6, 0.08, 0.02, a),
      ];
    case 'bottle': // бутылка: тело, горлышко, крышка
      return [
        box(0, 0.1, 0, 0.6, 0.2, 0.6, c),
        box(0, 0.225, 0, 0.32, 0.05, 0.32, c),
        box(0, 0.265, 0, 0.36, 0.03, 0.36, a),
        box(0, 0.09, 0.31, 0.62, 0.06, 0.02, a),
      ];
    case 'loaf': // буханка: низкая и длинная вглубь, светлая корочка сверху
      return [
        box(0, 0.05, 0, 0.88, 0.1, 1.4, c),
        box(0, 0.115, 0, 0.66, 0.03, 1.2, a),
      ];
    case 'bunch': // связка: три банана-столбика, тёмные хвостики сверху
      return [
        box(-0.28, 0.07, 0, 0.24, 0.14, 0.4, c),
        box(0, 0.08, 0.05, 0.24, 0.16, 0.4, c),
        box(0.28, 0.07, 0, 0.24, 0.14, 0.4, c),
        box(0, 0.17, 0.05, 0.14, 0.03, 0.14, a),
      ];
    case 'cup': // стаканчик с крышкой
      return [
        box(0, 0.06, 0, 0.62, 0.12, 0.62, c),
        box(0, 0.13, 0, 0.68, 0.02, 0.68, a),
      ];
    case 'tray': // лоток яиц: плоская коробка и четыре яйца сверху
      return [
        box(0, 0.03, 0, 0.92, 0.06, 1.2, c),
        box(-0.22, 0.08, -0.28, 0.3, 0.05, 0.3, a),
        box(0.22, 0.08, -0.28, 0.3, 0.05, 0.3, a),
        box(-0.22, 0.08, 0.28, 0.3, 0.05, 0.3, a),
        box(0.22, 0.08, 0.28, 0.3, 0.05, 0.3, a),
      ];
    case 'wedge': // кусок сыра: ступеньками, корка снизу
      return [
        box(0, 0.015, 0, 0.9, 0.03, 1.0, a),
        box(0, 0.05, 0, 0.9, 0.04, 1.0, c),
        box(0.12, 0.09, 0, 0.66, 0.04, 1.0, c),
        box(0.24, 0.13, 0, 0.42, 0.04, 1.0, c),
      ];
    case 'pack': // пачка: плоский брусок «лицом» к сборщику, окошко на лице
      return [
        box(0, 0.11, 0, 0.86, 0.22, 0.5, c),
        box(0, 0.12, 0.26, 0.5, 0.1, 0.02, a),
      ];
    case 'bag': // пакет чипсов: брусок, спайка сверху, логотип на лице
      return [
        box(0, 0.1, 0, 0.84, 0.2, 0.42, c),
        box(0, 0.215, 0, 0.88, 0.03, 0.3, c),
        box(0, 0.11, 0.22, 0.42, 0.08, 0.02, a),
      ];
    case 'jar': // банка: тело, крышка, этикетка
      return [
        box(0, 0.08, 0, 0.7, 0.16, 0.7, c),
        box(0, 0.175, 0, 0.74, 0.03, 0.74, a),
        box(0, 0.08, 0.36, 0.56, 0.07, 0.02, a),
      ];
  }
}
